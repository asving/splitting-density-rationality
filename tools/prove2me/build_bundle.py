def selftest(src, sol_dir):
    g = Gen(src)
    by_name = {}
    for full, ds in g.declared.items():
        for d in ds:
            if d["it"]["kind"] in ("theorem", "lemma"):
                by_name.setdefault(rename(full), []).append(d)
    c = collections.Counter()
    examples = collections.defaultdict(list)
    for name, t in sorted(g.thm_nodes.items()):
        ds = by_name.get(name, [])
        if len(ds) != 1:
            c["skipped: %d source declarations" % len(ds)] += 1
            continue
        d = ds[0]
        if platform_path(d["rel"]) != t["source_path"]:
            c["skipped: different file"] += 1
            continue
        try:
            n = g.node(d["rel"], d["it"])
        except AssertionError:
            c["skipped: not parsed"] += 1
            continue
        c["compared"] += 1
        pre = t["preamble"]
        p_imports = t["imports"]
        p_tail = pre.split("set_option autoImplicit false\n\n", 1)[1].rstrip("\n").split("\n")
        checks = [
            ("definition imports", [i for i in p_imports if i.startswith("Definitions.")] == n["def_imports"]),
            ("Mathlib imports", [i for i in p_imports if i.startswith("Mathlib")] == n["ext"]),
            ("theorem imports (ordered)", [i for i in p_imports if i.startswith("Theorems.")] == n["thm_imports"]),
            ("theorem imports (as a set)", set(i for i in p_imports if i.startswith("Theorems.")) == set(n["thm_imports"])),
            ("preamble tail", p_tail == n["tail"]),
            ("formal statement", t["statement"] == n["formal"]),
            ("whole statement file", pre + "\n" + t["statement"] + "\n" == n["preamble"] + "\n" + n["formal"] + "\n"),
        ]
        for label, ok in checks:
            c[(label, ok)] += 1
            if not ok and len(examples[label]) < 6:
                examples[label].append(name)
        if not checks[3][1]:
            mine = set(n["thm_imports"])
            theirs = set(i for i in p_imports if i.startswith("Theorems."))
            c[("theorem imports: I list more", bool(mine - theirs))] += 1
            c[("theorem imports: I miss some", bool(theirs - mine))] += 1
            if theirs - mine and len(examples["missed imports"]) < 8:
                examples["missed imports"].append((name, sorted(theirs - mine)[:3]))
            if mine - theirs and len(examples["extra imports"]) < 8:
                examples["extra imports"].append((name, sorted(mine - theirs)[:3]))
        if sol_dir:
            sp = os.path.join(sol_dir, "Sol_%s.lean" % t["slug"])
            if os.path.exists(sp):
                _, sbody = split_export_header(read(sp))
                c[("solution byte-identical", sbody == n["solution"])] += 1
                strip = lambda s: re.sub(r"(?<![\w.])TypeDensity\.(Tests\.)?(?=[A-Za-z_])", "", s)
                same = strip(sbody) == strip(n["solution"])
                c[("solution identical up to qualification", same)] += 1
                if not same and len(examples["solution layout"]) < 6:
                    examples["solution layout"].append(name)
                if same and sbody != n["solution"]:
                    # token-level: where the texts differ, who has the longer (qualified) form?
                    a = re.findall(r"\S+", sbody)
                    b = re.findall(r"\S+", n["solution"])
                    mine_more = theirs_more = 0
                    if len(a) == len(b):
                        for x, y in zip(a, b):
                            if x != y:
                                if len(y) > len(x):
                                    mine_more += 1
                                else:
                                    theirs_more += 1
                                    if len(examples["exporter qualified, generator did not"]) < 12:
                                        examples["exporter qualified, generator did not"].append((name, x, y))
                    c[("qualification: only I qualify more", theirs_more == 0)] += 1
    for k, v in sorted(c.items(), key=str):
        print(v, k)
    for k, v in examples.items():
        print("examples,", k, ":", v)
    return 0


