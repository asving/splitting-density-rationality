def split_export_header(text):
    lines = text.split("\n")
    i = 0
    while i < len(lines) and lines[i].startswith("--"):
        i += 1
    return lines[:i], "\n".join(lines[i + 1:])


def header_field(header, key):
    out = []
    on = False
    for ln in header:
        m = re.match(r"^-- %s\s*: (.*)$" % key, ln)
        if m:
            return m.group(1).strip()
        if ln == "-- %s:" % key:
            on = True
            continue
        if on:
            if ln.startswith("--   ") or ln == "--":
                out.append(ln[5:])
            else:
                break
    return "\n".join(out) if out else None


def load_platform():
    thm = {}       # name -> dict
    homes = {}     # declared name -> definition module
    def_mods = set()
    tdir = os.path.join(PLATFORM, "Theorems")
    for fn in sorted(os.listdir(tdir)):
        if not fn.startswith("Thm_TypeDensity"):
            continue
        header, body = split_export_header(read(os.path.join(tdir, fn)))
        if not header or not header[0].startswith("-- Prove2me |"):
            continue  # a staged bundle file, not a platform file
        name = header_field(header, "name")
        m = re.match(r"^(\S+)#L(\d+)-L(\d+)$", header_field(header, "source"))
        i = body.rfind("\n\ntheorem ")
        pre = body[:i + 1]
        thm[name] = dict(slug=fn[len("Thm_"):-len(".lean")], source_path=m.group(1),
                         source_line=int(m.group(2)), statement=body[i + 2:].rstrip("\n"),
                         preamble=pre, status=header_field(header, "status"),
                         title=header_field(header, "title"),
                         imports=re.findall(r"^import (\S+)", body, flags=re.M))
    ddir = os.path.join(PLATFORM, "Definitions")
    for fn in sorted(os.listdir(ddir)):
        if not fn.startswith("Def_TypeDensity"):
            continue
        path = os.path.join(ddir, fn)
        header, body = split_export_header(read(path))
        if not header or not header[0].startswith("-- Prove2me |"):
            continue
        mod = "Definitions." + fn[:-len(".lean")]
        def_mods.add(mod)
        items, _ = scan(path)
        for it in items:
            if it["type"] == "cmd" and it.get("name") and it["kind"] in DECL_KINDS:
                full = (it["namespace"] + "." if it["namespace"] else "") + it["name"]
                homes[full] = dict(module=mod, kind=it["kind"], private="private" in it["mods"],
                                   text=it["text"])
    return thm, homes, def_mods


