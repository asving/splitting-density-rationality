class Gen:
    def __init__(self, src):
        self.src = src
        self.thm_nodes, self.homes, self.platform_defs = load_platform()
        self.scans = {}
        self.declared = {}      # source full name -> list of dict(rel, it)
        for top in ("SurfaceBlowup", "Tests"):
            for dp, _, fns in os.walk(os.path.join(src, top)):
                for fn in sorted(fns):
                    if fn.endswith(".lean"):
                        rel = os.path.relpath(os.path.join(dp, fn), src)
                        items, lines = scan(os.path.join(dp, fn))
                        self.scans[rel] = (items, lines)
                        for it in items:
                            if it["type"] == "cmd" and it.get("name") and it["kind"] in DECL_KINDS:
                                full = (it["namespace"] + "." if it["namespace"] else "") + it["name"]
                                self.declared.setdefault(full, []).append(dict(rel=rel, it=it))
        self.new_public = {}    # source full name -> dict(rel, it, name) for nodes added by the bundle
        self._closure = {}

    # -- imports ---------------------------------------------------------------------------
    def module_imports(self, mod):
        out = []
        for ln in read(os.path.join(self.src, mod.replace(".", "/") + ".lean")).split("\n"):
            m = re.match(r"^import\s+(\S+)", ln)
            if m:
                out.append(m.group(1))
        return out

    def closure(self, rel, own_def_exists):
        key = (rel, own_def_exists)
        if key in self._closure:
            return self._closure[key]
        mod = rel[:-len(".lean")].replace("/", ".")
        seen = set()
        post = []
        ext = []

        def visit(m):
            if m in seen:
                return
            seen.add(m)
            imps = self.module_imports(m)
            for i in imps:
                if is_project(i):
                    visit(i)
            for i in imps:
                if not is_project(i) and i not in ext:
                    ext.append(i)
            post.append(m)

        visit(mod)
        defs = ["Definitions.Def_" + def_name(m) for m in post[:-1]
                if "Definitions.Def_" + def_name(m) in self.platform_defs]
        own = "Definitions.Def_" + def_name(mod)
        if own in self.platform_defs or own_def_exists:
            defs.append(own)
        self._closure[key] = (defs, ext, own)
        return self._closure[key]

    # -- name resolution -------------------------------------------------------------------
    @staticmethod
    def chain(namespace, decl_name=None):
        full = namespace
        if decl_name and "." in decl_name:
            full = namespace + "." + decl_name.rsplit(".", 1)[0]
        parts = full.split(".")
        return [".".join(parts[:k]) for k in range(len(parts), 0, -1)]

    def resolve(self, tok, chain):
        comps = tok.split(".")
        for k in range(len(comps), 0, -1):
            pre = ".".join(comps[:k])
            for ns in chain:
                if ns + "." + pre in self.declared:
                    return ns + "." + pre, k
            if pre in self.declared:        # already written with its full name
                return pre, k
        return None, 0

    def refs_in(self, text, chain):
        out = collections.OrderedDict()
        for (_, _, tok, dot) in idents(text):
            if dot:
                continue
            full, _ = self.resolve(tok, chain)
            if full:
                out.setdefault(tok, full)
        return out

    def qualify(self, text, chain):
        out = []
        last = 0
        for (s, e, tok, dot) in idents(text):
            if dot:
                continue
            full, k = self.resolve(tok, chain)
            if not full:
                continue
            comps = tok.split(".")
            out.append(text[last:s])
            out.append(rename(full) + "".join("." + c for c in comps[k:]))
            last = e
        out.append(text[last:])
        return "".join(out)

    def decl_in_file(self, full, rel):
        for d in self.declared.get(full, []):
            if d["rel"] == rel:
                return d
        return None

    # -- one theorem node ------------------------------------------------------------------
    def node(self, rel, it, own_def_exists=False):
        items = self.scans[rel][0]
        chain = self.chain(it["namespace"], it["name"])
        src_name = it["namespace"] + "." + it["name"]
        name = rename(src_name)
        sig, rest = split_statement(it["text"])
        m = re.match(r"^((?:@\[[^\]]*\]\s*)*(?:(?:private|protected|nonrec|noncomputable)\s+)*)(theorem|lemma)\s+(\S+)",
                     sig)
        assert m and m.group(3) == it["name"], sig[:80]
        after_name = sig[m.end():]

        def is_helper(full):
            d = self.decl_in_file(full, rel)
            return (d is not None and "private" in d["it"].get("mods", [])
                    and rename(full) not in self.thm_nodes and rename(full) not in self.homes)

        helpers = []

        def add_helpers(text, ch):
            for tok, full in self.refs_in(text, ch).items():
                if is_helper(full):
                    d = self.decl_in_file(full, rel)
                    if d not in helpers:
                        helpers.append(d)
                        add_helpers(d["it"]["text"], self.chain(d["it"]["namespace"], d["it"]["name"]))

        add_helpers(it["text"], chain)
        helpers.sort(key=lambda d: d["it"]["a"])
        all_refs = collections.OrderedDict()
        for tok, full in self.refs_in(it["text"], chain).items():
            all_refs.setdefault(full, "own text")
        for d in helpers:
            ch = self.chain(d["it"]["namespace"], d["it"]["name"])
            for tok, full in self.refs_in(d["it"]["text"], ch).items():
                all_refs.setdefault(full, "pasted helper " + d["it"]["name"])
        all_refs.pop(src_name, None)
        for d in helpers:
            all_refs.pop(d["it"]["namespace"] + "." + d["it"]["name"], None)

        thm_deps = []
        ref_rows = []
        defs, ext, own = self.closure(rel, own_def_exists)
        for full, via in all_refs.items():
            pname = rename(full)
            if pname in self.thm_nodes:
                t = self.thm_nodes[pname]
                mod = "Theorems.Thm_" + t["slug"]
                thm_deps.append(((t["source_path"], t["source_line"]), mod, pname))
                ref_rows.append(dict(name=pname, home=mod, kind="platform theorem", via=via))
            elif full in self.new_public:
                d = self.new_public[full]
                key = (platform_path(d["rel"]), (d["it"]["doc"][0] if d["it"]["doc"] else d["it"]["a"]) + 1)
                mod = "Theorems.Thm_" + d["name"].replace(".", "_")
                thm_deps.append((key, mod, d["name"]))
                ref_rows.append(dict(name=pname, home=mod, kind="new theorem", via=via))
            elif pname in self.homes:
                ref_rows.append(dict(name=pname, home=self.homes[pname]["module"],
                                     kind="platform %s in a definition module" % self.homes[pname]["kind"],
                                     via=via))
            elif rel in LOCAL_INSTANCES and full.rsplit(".", 1)[-1] in LOCAL_INSTANCES[rel]:
                ref_rows.append(dict(name=pname, home=own, kind="new instance", via=via))
            else:
                ref_rows.append(dict(name=pname, home=None, kind="NOT FOUND", via=via))
        thm_deps.sort(key=lambda x: x[0])
        thm_imports = [x[1] for x in thm_deps]
        imports = defs + thm_imports + ext

        # preamble tail: namespace opens, the file's live open lines, live variable lines
        ns_parts = it["namespace"].split(".")
        tail = ["open " + " ".join(rename(".".join(ns_parts[:k])) for k in range(1, len(ns_parts) + 1))]
        scope = []
        live = []
        for other in items:
            if other["type"] != "cmd":
                continue
            if other["a"] >= it["a"]:
                break
            if other["kind"] in ("namespace", "section"):
                scope.append(len(live))
            elif other["kind"] == "end":
                if scope:
                    del live[scope.pop():]
            elif other["kind"] in ("open", "variable"):
                live.append(other)
        tail += [rename(o["text"]) for o in live if o["kind"] == "open"]
        tail += [rename(o["text"]) for o in live if o["kind"] == "variable"]
        if rel in LOCAL_INSTANCES:
            tail.append("attribute [local instance] " + " ".join(
                rename(it["namespace"]) + "." + x for x in LOCAL_INSTANCES[rel]))
        preamble = "".join("import %s\n" % i for i in imports) + "set_option autoImplicit false\n\n" + \
            "\n".join(tail) + "\n"
        formal = "theorem " + name + rename(after_name).rstrip() + " := by sorry"

        sol = [GEN_LINE % platform_path(rel)]
        sol += ["import %s" % i for i in imports]
        sol += ["", "set_option autoImplicit false", ""]
        if helpers:
            block = []
            closers = []
            last_a = max(d["it"]["a"] for d in helpers)
            for other in items:
                if other["type"] != "cmd" or other["a"] > last_a:
                    continue
                k = other["kind"]
                if k in ("open", "variable"):
                    block.append(rename(other["text"]))
                elif k == "namespace":
                    block.append("namespace " + rename(other["name"]))
                    closers.append("end " + rename(other["name"]))
                elif k == "section":
                    block.append(other["text"])
                    closers.append(("end " + other["name"]).rstrip())
                elif k == "end":
                    block.append(rename(other["text"]))
                    closers.pop()
                elif any(d["it"] is other for d in helpers):
                    block.append(rename((other["doc_text"] + "\n" if other["doc_text"] else "") + other["text"]))
            sol.append("\n\n".join(block))
            sol.append("")
            sol.append("\n".join(reversed(closers)))
            sol.append("")
        sol_tail = list(tail)
        if "." in it["name"]:
            sol_tail.insert(1, "open " + rename(it["namespace"] + "." + it["name"].rsplit(".", 1)[0]))
        sol += sol_tail
        sol.append("")
        sol.append("theorem solution" + self.qualify(after_name + (rest or ""), chain))
        return dict(
            name=name, slug=name.replace(".", "_"), rel=rel, src_name=src_name,
            preamble=preamble, formal=formal, solution="\n".join(sol) + "\n", imports=imports,
            def_imports=defs, thm_imports=thm_imports, ext=ext, tail=tail,
            platform_imports=defs + thm_imports, thm_deps=[x[2] for x in thm_deps],
            helpers=[d["it"]["name"] for d in helpers], refs=ref_rows,
            src_statement=rename(sig).rstrip())


