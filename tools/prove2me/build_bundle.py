def build():
    g = Gen(os.path.join(ROOT, "src-v1.2.0"))
    new = []
    for rel in NEW_FILES:
        items, _ = g.scans[rel]
        assert not any(it["type"] == "cmd" and it["kind"] in ("def", "abbrev", "structure", "inductive",
                                                             "class", "opaque", "other") for it in items), rel
        for it in items:
            if it["type"] == "cmd" and it["kind"] in ("theorem", "lemma") and "private" not in it["mods"]:
                assert not it["attrs"], "attribute on a new theorem: not covered by the conventions"
                full = it["namespace"] + "." + it["name"]
                g.new_public[full] = dict(rel=rel, it=it, name=rename(full))
                new.append((rel, it))
    has_inst = {rel: any(it["type"] == "cmd" and it["kind"] == "instance" for it in g.scans[rel][0])
                for rel in NEW_FILES}
    out_nodes = []
    for rel, it in new:
        n = g.node(rel, it, own_def_exists=has_inst[rel])
        n["title"] = TITLES.get(n["name"]) or make_title(it["doc_text"])
        n["nl"] = flatten_doc(it["doc_text"])
        n["source"] = "%s#L%d-L%d" % (platform_path(rel), it["doc"][0] + 1, it["b"] + 1)
        out_nodes.append(n)

    # ---- definition module(s) for Tests/PadicInt.lean -------------------------------------
    rel = "Tests/PadicInt.lean"
    items, lines = g.scans[rel]
    defs, ext, own = g.closure(rel, True)
    defname = own[len("Definitions.Def_"):]
    def_imports = defs[:-1]
    moddoc = [it for it in items if it["type"] == "moddoc"][0]
    mm = re.match(r"^/-!\n(.*)\n-/$", "\n".join(lines[moddoc["a"]:moddoc["b"] + 1]), flags=re.S)
    def_nl = rename(mm.group(1))
    def_title = "Definitions of Tests.PadicInt"

    def decl_text(it):
        text = it["text"]
        if it["kind"] == "instance" and not it.get("name"):
            nm = INSTANCE_NAMES[(rel, it["a"] + 1)]
            text = re.sub(r"^((?:\w+\s+)*?)instance\b", lambda m: m.group(0) + " " + nm, text, count=1)
        return rename((it["doc_text"] + "\n" if it.get("doc_text") else "") + text)

    def def_text(thm_imports, keep_theorems):
        block = []
        for it in items:
            if it["type"] != "cmd" or it["kind"] in ("import", "hash"):
                continue
            k = it["kind"]
            if k == "namespace":
                block.append("namespace " + rename(it["name"]))
            elif k in ("open", "variable", "section", "end"):
                block.append(rename(it["text"]))
            elif k == "instance" or (k in ("theorem", "lemma") and keep_theorems):
                block.append(decl_text(it))
            elif k not in ("theorem", "lemma"):
                raise SystemExit("unexpected command kind %s in %s" % (k, rel))
        head = [GEN_LINE % platform_path(rel)]
        head += ["import %s" % i for i in def_imports + thm_imports + ext]
        head.append("set_option autoImplicit false")
        return "\n".join(head) + "\n\n" + "\n\n".join(block) + "\n"

    padic = [n for n in out_nodes if n["rel"] == rel]
    padic_names = {n["name"] for n in padic}
    keyed = {}
    for n in padic:
        for mod, nm in zip(n["thm_imports"], n["thm_deps"]):
            if nm in padic_names:
                continue
            if nm in g.thm_nodes:
                keyed[mod] = (g.thm_nodes[nm]["source_path"], g.thm_nodes[nm]["source_line"])
            else:
                o = [x for x in out_nodes if x["name"] == nm][0]
                m2 = re.match(r"^(\S+)#L(\d+)-", o["source"])
                keyed[mod] = (m2.group(1), int(m2.group(2)))
    alt_thm_imports = sorted(keyed, key=lambda k: keyed[k])
    def_B = def_text([], False)
    def_A = def_text(alt_thm_imports, True)

    # ---- text-level checks ----------------------------------------------------------------
    problems = []
    seen = set()
    sorry_re = re.compile(r"(?<![\w.])sorry(?![\w'])")
    for n in out_nodes:
        if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$", n["name"]):
            problems.append("non-conservative name " + n["name"])
        if n["name"] in g.thm_nodes or n["name"] in g.homes or n["name"] in seen:
            problems.append("name already on the platform: " + n["name"])
        seen.add(n["name"])
        if not n["formal"].startswith("theorem " + n["name"] + " ") or not n["formal"].endswith(" := by sorry"):
            problems.append("bad formal statement shape: " + n["name"])
        if "/--" in n["formal"] or "/--" in n["preamble"]:
            problems.append("docstring in statement: " + n["name"])
        if sorry_re.search(n["solution"]):
            problems.append("sorry in solution: " + n["name"])
        if not re.search(r"^theorem solution\b", n["solution"], flags=re.M):
            problems.append("no top-level theorem solution: " + n["name"])
        if ("import Theorems.Thm_%s\n" % n["slug"]) in n["solution"]:
            problems.append("solution imports its own target: " + n["name"])
        if len(n["title"]) > 200 or not n["title"]:
            problems.append("bad title length: " + n["name"])
        for r in n["refs"]:
            if r["home"] is None:
                problems.append("no platform home for %s (used by %s)" % (r["name"], n["name"]))
            elif r["home"] not in n["imports"]:
                problems.append("home %s of %s is not imported by %s" % (r["home"], r["name"], n["name"]))
    if own in g.platform_defs:
        problems.append("definition name already on the platform: " + defname)
    for txt, label in ((def_A, "definition (module variant)"), (def_B, "definition")):
        if sorry_re.search(txt):
            problems.append("sorry in " + label)

    # ---- write ----------------------------------------------------------------------------
    for sub in ("definitions", "problems", "solutions", "alt"):
        p = os.path.join(BUNDLE, sub)
        if os.path.isdir(p):
            shutil.rmtree(p)
    alt_dir = os.path.join(BUNDLE, "alt", "padicint-as-module")
    for p in (os.path.join(BUNDLE, "definitions"), os.path.join(BUNDLE, "problems"),
              os.path.join(BUNDLE, "solutions"), alt_dir):
        os.makedirs(p)

    def write(path, text):
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)

    def dump(path, obj):
        write(path, json.dumps(obj, ensure_ascii=False, indent=2) + "\n")

    def sha(text):
        return hashlib.sha256(text.encode("utf-8")).hexdigest()

    def def_payload(text):
        return collections.OrderedDict([
            ("definition_name", defname), ("definition_title", def_title), ("definition", text),
            ("natural_language_statement", def_nl), ("tags", TAGS), ("env", ENV_REV)])

    def platform_mods(text):
        return [i for i in re.findall(r"^import (\S+)", text, flags=re.M) if not i.startswith("Mathlib")]

    order_main = []
    order_alt = []

    def add(order, kind, name, payload, lean, mods):
        order.append(collections.OrderedDict([
            ("step", len(order) + 1), ("kind", kind), ("name", name),
            ("payload", os.path.relpath(payload, ROOT)), ("lean", os.path.relpath(lean, ROOT)),
            ("imports", mods)]))

    def paths(n):
        return (os.path.join(BUNDLE, "problems", "Thm_%s.lean" % n["slug"]),
                os.path.join(BUNDLE, "problems", "Thm_%s.payload.json" % n["slug"]),
                os.path.join(BUNDLE, "solutions", "Sol_%s.lean" % n["slug"]),
                os.path.join(BUNDLE, "solutions", "Sol_%s.payload.json" % n["slug"]))

    def add_theorem(order, n):
        thm_lean, thm_json, sol_lean, sol_json = paths(n)
        add(order, "problem", n["name"], thm_json, thm_lean, n["platform_imports"])
        add(order, "solution", n["name"], sol_json, sol_lean, n["platform_imports"])

    for n in out_nodes:
        thm_lean, thm_json, sol_lean, sol_json = paths(n)
        write(thm_lean, n["preamble"] + "\n" + n["formal"] + "\n")
        dump(thm_json, collections.OrderedDict([
            ("problems", [collections.OrderedDict([
                ("theorem_name", n["name"]), ("theorem_title", n["title"]),
                ("formal_statement", n["formal"]), ("natural_language_statement", n["nl"]),
                ("preamble", n["preamble"]), ("source", n["source"]), ("tags", TAGS)])]),
            ("env", ENV_REV)]))
        write(sol_lean, n["solution"])
        dump(sol_json, collections.OrderedDict([
            ("endpoint", "POST /api/v1/verify (multipart/form-data)"),
            ("theorem_name", n["name"]),
            ("form", collections.OrderedDict([
                ("theorem_id", "<theorem_id of %s, read from the upload state>" % n["name"]),
                ("proof_type", "prove")])),
            ("file_field", "file"), ("file", "Sol_%s.lean" % n["slug"]),
            ("file_sha256", sha(n["solution"]))]))

    def_lean = os.path.join(BUNDLE, "definitions", "Def_%s.lean" % defname)
    def_json = os.path.join(BUNDLE, "definitions", "Def_%s.payload.json" % defname)
    write(def_lean, def_B)
    dump(def_json, def_payload(def_B))
    alt_lean = os.path.join(alt_dir, "Def_%s.lean" % defname)
    alt_json = os.path.join(alt_dir, "Def_%s.payload.json" % defname)
    write(alt_lean, def_A)
    dump(alt_json, def_payload(def_A))

    for n in out_nodes:
        if n["rel"] != rel:
            add_theorem(order_main, n)
            add_theorem(order_alt, n)
    add(order_main, "definition", defname, def_json, def_lean, platform_mods(def_B))
    for n in padic:
        add_theorem(order_main, n)
    add(order_alt, "definition", defname, alt_json, alt_lean, platform_mods(def_A))

    # upload order: whatever an entry imports must be published, and proved, before it
    for order in (order_main, order_alt):
        done = set()
        for e in order:
            for mod in e["imports"]:
                kind, base = mod.split(".", 1)
                if os.path.exists(os.path.join(PLATFORM, kind, base + ".lean")) and \
                        read(os.path.join(PLATFORM, kind, base + ".lean")).startswith("-- Prove2me |"):
                    continue
                if mod not in done:
                    problems.append("order: %s %s imports %s before it is available" % (e["kind"], e["name"], mod))
            if e["kind"] == "definition":
                done.add("Definitions.Def_" + e["name"])
            elif e["kind"] == "solution":
                done.add("Theorems.Thm_" + e["name"].replace(".", "_"))

    meta = [("env", ENV_REV), ("toolchain", "leanprover/lean4:v4.33.1"), ("source_tag", "v1.2.0"),
            ("api_base", "https://prove2.me/api/v1")]
    dump(os.path.join(ROOT, "ORDER.json"), collections.OrderedDict(
        meta + [("variant", "padicint-as-nodes"), ("nodes", order_main)]))
    dump(os.path.join(ROOT, "ORDER.padicint-as-module.json"), collections.OrderedDict(
        meta + [("variant", "padicint-as-module"), ("nodes", order_alt)]))

    dump(os.path.join(BUNDLE, "nodes.json"), collections.OrderedDict([
        ("definition", collections.OrderedDict([
            ("name", defname), ("title", def_title),
            ("imports", platform_mods(def_B)), ("alt_imports", platform_mods(def_A))])),
        ("theorems", [collections.OrderedDict([
            ("name", n["name"]), ("source", n["source"]), ("title", n["title"]),
            ("helpers_pasted", n["helpers"]), ("theorem_imports", n["thm_imports"]),
            ("definition_imports", n["def_imports"]), ("mathlib_imports", n["ext"]),
            ("references", n["refs"]), ("source_statement", n["src_statement"])]) for n in out_nodes]),
        ("problems_found", problems)]))

    print("theorem nodes: %d, definition module: %s" % (len(out_nodes), defname))
    print("ORDER.json steps: %d ; ORDER.padicint-as-module.json steps: %d" % (len(order_main), len(order_alt)))
    if problems:
        print("PROBLEMS:")
        for p in problems:
            print("  -", p)
        return 1
    print("text-level self-checks passed (nothing was compiled)")
    return 0


