DECL_RE = re.compile(
    r"^(?P<attrs>(?:@\[[^\]]*\]\s*)*)"
    r"(?P<mods>(?:(?:private|protected|noncomputable|nonrec|unsafe|partial|local|scoped)\s+)*)"
    r"(?P<kind>theorem|lemma|def|abbrev|instance|structure|inductive|class|opaque|axiom)\b"
    r"[ \t]*(?P<name>[^\s:({\[]+)?")


def scan(path):
    """Top-level commands of a Lean file, in order (every line starting in column 0 starts one)."""
    lines = read(path).split("\n")
    n = len(lines)
    tops = []
    j = 0
    while j < n:
        ln = lines[j]
        if ln.startswith("/-"):
            k = j
            while "-/" not in lines[k][(3 if k == j else 0):]:
                k += 1
            kind = "moddoc" if ln.startswith("/-!") else ("doc" if ln.startswith("/--") else "comment")
            tops.append([kind, j, k])
            j = k + 1
            continue
        if ln and not ln[0].isspace() and not ln.startswith("--"):
            tops.append(["cmd", j, j])
        j += 1
    for idx, t in enumerate(tops):
        if t[0] != "cmd":
            continue
        nxt = tops[idx + 1][1] if idx + 1 < len(tops) else n
        e = nxt - 1
        while e > t[1] and (lines[e].strip() == "" or lines[e].startswith("--")):
            e -= 1
        t[2] = e
    items = []
    stack = []
    doc = None
    for kind, a, b in tops:
        if kind in ("moddoc", "comment"):
            doc = None
            items.append(dict(type=kind, a=a, b=b))
            continue
        if kind == "doc":
            doc = (a, b)
            continue
        ln = lines[a]
        it = dict(type="cmd", a=a, b=b, text="\n".join(lines[a:b + 1]), doc=None, kind=None,
                  stack=list(stack), doc_text=None)
        m = re.match(r"^namespace\s+(\S+)", ln)
        if m:
            it["kind"] = "namespace"
            it["name"] = m.group(1)
            stack.append(("namespace", m.group(1)))
        elif re.match(r"^(noncomputable\s+)?section\b", ln):
            it["kind"] = "section"
            words = ln.split()
            it["name"] = words[-1] if words[-1] != "section" else ""
            stack.append(("section", it["name"]))
        elif re.match(r"^end\b", ln):
            it["kind"] = "end"
            if stack:
                stack.pop()
        elif re.match(r"^open\b", ln) and not ln.rstrip().endswith(" in"):
            it["kind"] = "open"
        elif re.match(r"^variable\b", ln):
            it["kind"] = "variable"
        elif re.match(r"^import\b", ln):
            it["kind"] = "import"
        elif re.match(r"^#", ln):
            it["kind"] = "hash"
        else:
            dm = DECL_RE.match(ln)
            if dm:
                it["kind"] = dm.group("kind")
                it["name"] = dm.group("name")
                it["mods"] = dm.group("mods").split()
                it["attrs"] = dm.group("attrs").strip()
                it["namespace"] = ".".join(x[1] for x in stack if x[0] == "namespace")
                it["doc"] = doc
                it["doc_text"] = "\n".join(lines[doc[0]:doc[1] + 1]) if doc else None
            else:
                it["kind"] = "other"
        doc = None
        items.append(it)
    return items, lines


# --------------------------------------------------------------------------------------------
# Lean identifier lexer
# --------------------------------------------------------------------------------------------

ID_START = ("A-Za-z_α-κμ-ωΑ-ΞΠΡΣ-Ω"
            "ἀ-῾℀-⅏\U0001d49c-\U0001d59f")
ID_REST = ID_START + "0-9'!?₀-ₜᵢ-ᵪ"
ATOM = "[" + ID_START + "][" + ID_REST + "]*"
IDENT_RE = re.compile(ATOM + r"(?:\." + ATOM + r")*")
REST_RE = re.compile("[" + ID_REST + "]")


def idents(text):
    """Yield (start, end, token, preceded_by_dot) for identifiers outside comments and strings."""
    i = 0
    n = len(text)
    while i < n:
        if text.startswith("--", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        if text.startswith("/-", i):
            depth = 1
            j = i + 2
            while j < n and depth > 0:
                if text.startswith("/-", j):
                    depth += 1
                    j += 2
                elif text.startswith("-/", j):
                    depth -= 1
                    j += 2
                else:
                    j += 1
            i = j
            continue
        if text[i] == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            i = j + 1
            continue
        m = IDENT_RE.match(text, i)
        if m and m.end() > i:
            prev = text[i - 1] if i > 0 else ""
            if not (prev and REST_RE.match(prev)):
                yield (m.start(), m.end(), m.group(0), prev == ".")
            i = m.end()
            continue
        i += 1


def split_statement(text):
    """Split a declaration at the first `:=` outside brackets: (signature, rest starting at `:=`).
    Returns (text, None) if there is none (e.g. a declaration given by pattern matching)."""
    depth = 0
    i = 0
    n = len(text)
    while i < n:
        if text.startswith("--", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        c = text[i]
        if c in "([{⟨":
            depth += 1
        elif c in ")]}⟩":
            depth -= 1
        elif depth == 0 and text.startswith(":=", i):
            return text[:i], text[i:]
        i += 1
    return text, None


