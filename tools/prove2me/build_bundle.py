def docstring_inner(doc_text):
    t = doc_text.strip()
    assert t.startswith("/--") and t.endswith("-/")
    return t[3:-2].strip()


def flatten_doc(doc_text):
    """Join the lines of each paragraph; keep paragraph breaks and list items."""
    t = rename(docstring_inner(doc_text))
    paras = re.split(r"\n[ \t]*\n", t)
    out = []
    for p in paras:
        blocks = []
        for ln in p.split("\n"):
            s = ln.strip()
            if re.match(r"^[*-] ", s) or not blocks:
                blocks.append(s)
            else:
                blocks[-1] += " " + s
        out.append("\n".join(blocks))
    return "\n\n".join(out)


def make_title(doc_text):
    first = flatten_doc(doc_text).split("\n\n")[0].replace("\n", " ")
    m = re.search(r"[.;] ", first)
    s = first[:m.start() + 1] if m else first
    return s[:200].rstrip()


